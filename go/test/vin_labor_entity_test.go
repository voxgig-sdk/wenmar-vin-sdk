// main.kit.test.live.strict is true (the default is true): a live
// request that fails, or a live test missing an input it needs,
// fails the test.
// An account with no record for a test to read skips it either way.
const vin_laborEntityLiveStrict = true


func TestVinLaborEntity(t *testing.T) {
	t.Run("instance", func(t *testing.T) {
		testsdk := sdk.TestSDK(nil, nil)
		ent := testsdk.VinLabor(nil)
		if ent == nil {
			t.Fatal("expected non-nil VinLaborEntity")
		}
	})

	t.Run("validate", func(t *testing.T) {
		if !fhHasFeature("validate") {
			t.Skip("feature not present in this SDK: validate")
		}
		client := sdk.TestSDK(nil, map[string]any{
			"feature": map[string]any{"validate": map[string]any{"active": true}},
		})
		_, err := client.VinLabor(nil).List(map[string]any{"id": 1}, nil)
		if sdkerr, ok := err.(*core.WenmarVinError); !ok || "validate_failed" != sdkerr.Code {
			t.Fatalf("expected validate_failed, got %v", err)
		}
	})

	t.Run("basic", func(tt *testing.T) {
		var t testing.TB = tt
		setup := vin_laborBasicSetup(nil)
		// Per-op sdk-test-control.json skip — basic test exercises a flow
		// with multiple ops; skipping any op skips the whole flow.
		_mode := "unit"
		if setup.live {
			_mode = "live"
		}
		for _, _op := range []string{"load"} {
			if _shouldSkip, _reason := isControlSkipped("entityOp", "vin_labor." + _op, _mode); _shouldSkip {
				if _reason == "" {
					_reason = "skipped via sdk-test-control.json"
				}
				t.Skip(_reason)
				return
			}
		}
		if setup.live {
			liveMiss(t, vin_laborEntityLiveStrict, "Live entity test blocked: %s", "the flow loads a vin_labor record it has no list to find")
		}
		client := setup.client
		_ = client

		// Bootstrap entity data from existing test data (no create step in flow).
		vinLaborRef01DataRaw := vs.Items(core.ToMapAny(vs.GetPath(setup.data, "existing.vin_labor")))
		var vinLaborRef01Data map[string]any
		if len(vinLaborRef01DataRaw) > 0 {
			vinLaborRef01Data = core.ToMapAny(vinLaborRef01DataRaw[0][1])
		}
		// Discard guards against Go's unused-var check when the flow's steps
		// happen not to consume the bootstrap data (e.g. list-only flows).
		_ = vinLaborRef01Data

		// LOAD
		vinLaborRef01Ent := client.VinLabor(nil)
		vinLaborRef01MatchDt0 := map[string]any{
			"id": vinLaborRef01Data["id"],
		}
		if v := setup.idmap["vin_id"]; v != nil {
			vinLaborRef01MatchDt0["vin_id"] = v
		} else {
			vinLaborRef01MatchDt0["vin_id"] = setup.idmap["vin01"]
		}
		vinLaborRef01DataDt0Loaded, err := vinLaborRef01Ent.Load(vinLaborRef01MatchDt0, nil)
		if err != nil {
			t.Fatalf("load failed: %v", err)
		}
		vinLaborRef01DataDt0LoadResult := core.ToMapAny(entityData(vinLaborRef01DataDt0Loaded))
		if vinLaborRef01DataDt0LoadResult == nil {
			t.Fatal("expected load result to be a map")
		}
		if vinLaborRef01DataDt0LoadResult["id"] != vinLaborRef01Data["id"] {
			t.Fatal("expected load result id to match")
		}

	})
}

func vin_laborBasicSetup(extra map[string]any) *entityTestSetup {
	loadEnvLocal()

	_, filename, _, _ := runtime.Caller(0)
	dir := filepath.Dir(filename)

	entityDataFile := filepath.Join(dir, "..", "..", ".sdk", "test", "entity", "vin_labor", "VinLaborTestData.json")

	entityDataSource, err := os.ReadFile(entityDataFile)
	if err != nil {
		panic("failed to read vin_labor test data: " + err.Error())
	}

	var entityData map[string]any
	if err := json.Unmarshal(entityDataSource, &entityData); err != nil {
		panic("failed to parse vin_labor test data: " + err.Error())
	}

	options := map[string]any{}
	options["entity"] = entityData["existing"]

	client := sdk.TestSDK(options, extra)

	// Generate idmap via transform, matching TS pattern.
	idmap, _ := vs.Transform(
		[]any{"vin_labor01", "vin_labor02", "vin_labor03", "vin01", "vin02", "vin03"},
		map[string]any{
			"`$PACK`": []any{"", map[string]any{
				"`$KEY`": "`$COPY`",
				"`$VAL`": []any{"`$FORMAT`", "upper", "`$COPY`"},
			}},
		},
	)

	// Whether *_ENTID supplied the idmap, read before envOverride consumes it:
	// without it, the ids a live flow binds are the fixture's synthetic ones.
	entidEnvRaw := os.Getenv("WENMAR_VIN_TEST_VIN_LABOR_ENTID")
	idmapOverridden := entidEnvRaw != "" && strings.HasPrefix(strings.TrimSpace(entidEnvRaw), "{")

	env := envOverride(map[string]any{
		"WENMAR_VIN_TEST_VIN_LABOR_ENTID": idmap,
		"WENMAR_VIN_TEST_LIVE":      "FALSE",
		"WENMAR_VIN_TEST_EXPLAIN":   "FALSE",
	})

	idmapResolved := core.ToMapAny(env["WENMAR_VIN_TEST_VIN_LABOR_ENTID"])
	if idmapResolved == nil {
		idmapResolved = core.ToMapAny(idmap)
	}

	if env["WENMAR_VIN_TEST_LIVE"] == "TRUE" {
		// An empty map, not a nil one: Merge returns nil when its last entry
		// is nil, and BasicSetup is normally called with no extras - so a
		// bare nil silently discarded the apikey and server values below.
		extraOpts := extra
		if extraOpts == nil {
			extraOpts = map[string]any{}
		}

		mergedOpts := vs.Merge([]any{
			// liveClientOptions() FIRST, so the generated fields below win:
			// sdk-test-control.json's test.client.options adds to the live
			// client, it does not redirect it.
			liveClientOptions(),
			map[string]any{
			},
			extraOpts,
		})
		client = sdk.NewWenmarVinSDK(core.ToMapAny(mergedOpts))
	}

	live := env["WENMAR_VIN_TEST_LIVE"] == "TRUE"
	return &entityTestSetup{
		client:        client,
		data:          entityData,
		idmap:         idmapResolved,
		env:           env,
		explain:       env["WENMAR_VIN_TEST_EXPLAIN"] == "TRUE",
		live:          live,
		syntheticOnly: live && !idmapOverridden,
		now:           time.Now().UnixMilli(),
	}
}
